-- 1. PROFIL USER (terhubung ke Supabase Auth)
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  username    text not null unique check (username ~ '^[a-z0-9_.]{3,20}$'),
  name        text not null check (char_length(name) between 2 and 80),
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  created_at  timestamptz not null default now()
);

-- Cek admin (dipakai di RLS). SECURITY DEFINER agar tidak rekursif ke RLS profiles.
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Buat profil otomatis saat user mendaftar. Role SELALU 'customer' (admin diset manual).
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username, name)
  values (
    new.id,
    lower(coalesce(nullif(new.raw_user_meta_data->>'username', ''), 'user' || substr(replace(new.id::text, '-', ''), 1, 8))),
    coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), 'Pelanggan')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Cek username sebelum daftar
create or replace function public.username_available(p_username text)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select not exists (select 1 from public.profiles where username = lower(p_username));
$$;

