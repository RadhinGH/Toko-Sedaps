-- 2. PRODUK (+ HPP dipisah agar modal tidak terlihat pembeli)
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  category    text not null check (category in ('women', 'men')),
  name        text not null check (char_length(name) between 2 and 120),
  type        text not null,
  material    text not null default 'Rajut Standar Ekspor',
  description text not null default '',
  price       integer not null check (price >= 0),
  sizes       jsonb,                        -- contoh: {"S":5,"M":5,"L":5} atau null (one-size)
  stock       integer not null default 0 check (stock >= 0),
  weight      integer not null default 300 check (weight > 0),
  images      text[] not null default '{}',
  rating      numeric(3,2) not null default 0,
  sold        integer not null default 0,
  views       integer not null default 0,
  is_new      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.product_costs (
  product_id  bigint primary key references public.products(id) on delete cascade,
  cost        integer not null default 0 check (cost >= 0)
);

-- Stok total selalu = jumlah stok per ukuran
create or replace function public.products_sync_stock()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.sizes is not null and jsonb_typeof(new.sizes) = 'object' and new.sizes <> '{}'::jsonb then
    if exists (select 1 from jsonb_each_text(new.sizes) e where e.value::int < 0) then
      raise exception 'Stok per ukuran tidak boleh negatif';
    end if;
    new.stock := (select coalesce(sum(e.value::int), 0) from jsonb_each_text(new.sizes) e);
  else
    new.sizes := null;
  end if;
  return new;
end;
$$;

drop trigger if exists products_sync_stock on public.products;
create trigger products_sync_stock
  before insert or update on public.products
  for each row execute function public.products_sync_stock();

