-- Buat pesanan: harga & stok diambil dari database, stok dipotong atomik.
create or replace function public.place_order(
  p_items    jsonb,          -- [{"id":1,"size":"M","qty":2}, ...]
  p_customer text,
  p_phone    text,
  p_address  text,
  p_city     text,
  p_courier  text,
  p_proof    text default null
)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_uid      uuid := auth.uid();
  v_item     jsonb;
  v_prod     public.products%rowtype;
  v_cost     integer;
  v_qty      integer;
  v_size     text;
  v_avail    integer;
  v_lines    jsonb := '[]'::jsonb;
  v_costs    jsonb := '[]'::jsonb;
  v_summary  text[] := '{}';
  v_subtotal integer := 0;
  v_hpp      integer := 0;
  v_weight   integer := 0;
  v_ship     integer;
  v_order    public.orders%rowtype;
begin
  if v_uid is null then raise exception 'Silakan login terlebih dahulu.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Keranjang kosong.';
  end if;
  if jsonb_array_length(p_items) > 50 then raise exception 'Terlalu banyak item dalam satu pesanan.'; end if;
  if coalesce(trim(p_customer), '') = '' or coalesce(trim(p_address), '') = '' or coalesce(trim(p_city), '') = '' then
    raise exception 'Lengkapi data penerima & alamat.';
  end if;
  if regexp_replace(coalesce(p_phone, ''), '[[:space:]-]', '', 'g') !~ '^0[0-9]{8,13}$' then
    raise exception 'Format nomor HP tidak valid.';
  end if;
  if p_courier not in ('JNE Express', 'SiCepat Reguler', 'GoSend Instant') then
    raise exception 'Kurir tidak valid.';
  end if;
  if p_proof is not null and p_proof not like (v_uid::text || '/%') then
    raise exception 'File bukti bayar tidak valid.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty  := (v_item->>'qty')::integer;
    v_size := nullif(v_item->>'size', '');
    if v_qty is null or v_qty < 1 or v_qty > 99 then raise exception 'Jumlah barang tidak valid.'; end if;

    select * into v_prod from public.products where id = (v_item->>'id')::bigint for update;
    if not found then raise exception 'Ada produk di keranjang yang sudah tidak tersedia.'; end if;

    if v_prod.sizes is not null then
      if v_size is null or not (v_prod.sizes ? v_size) then
        raise exception 'Pilih ukuran untuk %.', v_prod.name;
      end if;
      v_avail := (v_prod.sizes->>v_size)::integer;
      if v_avail < v_qty then
        raise exception 'Stok % ukuran % tidak cukup (sisa %).', v_prod.name, v_size, v_avail;
      end if;
      update public.products
        set sizes = jsonb_set(sizes, array[v_size], to_jsonb(v_avail - v_qty))
        where id = v_prod.id;
    else
      v_size := null;
      if v_prod.stock < v_qty then
        raise exception 'Stok % tidak cukup (sisa %).', v_prod.name, v_prod.stock;
      end if;
      update public.products set stock = stock - v_qty where id = v_prod.id;
    end if;

    v_cost := coalesce((select pc.cost from public.product_costs pc where pc.product_id = v_prod.id), 0);

    v_lines    := v_lines || jsonb_build_object('id', v_prod.id, 'name', v_prod.name, 'price', v_prod.price, 'size', v_size, 'quantity', v_qty);
    v_costs    := v_costs || jsonb_build_object('id', v_prod.id, 'size', v_size, 'cost', v_cost);
    v_summary  := v_summary || (v_prod.name || coalesce(' uk.' || v_size, '') || ' (x' || v_qty || ')');
    v_subtotal := v_subtotal + v_prod.price * v_qty;
    v_hpp      := v_hpp + v_cost * v_qty;
    v_weight   := v_weight + v_prod.weight * v_qty;
  end loop;

  v_ship := public.calc_shipping(p_city, p_courier, v_weight);

  insert into public.orders (user_id, customer, phone, address, city, courier, items, items_summary,
                             subtotal, shipping_fee, weight, total, payment_proof)
  values (v_uid, left(trim(p_customer), 80), left(trim(p_phone), 20), left(trim(p_address), 500), left(trim(p_city), 60),
          p_courier, v_lines, array_to_string(v_summary, ', '),
          v_subtotal, v_ship, v_weight, v_subtotal + v_ship, p_proof)
  returning * into v_order;

  insert into public.order_finance (order_id, hpp, profit, item_costs)
  values (v_order.id, v_hpp, v_subtotal - v_hpp, v_costs);

  return to_jsonb(v_order);
end;
$$;

-- Admin: setujui pembayaran -> Diproses (angka "terjual" baru dihitung di sini)
create or replace function public.approve_order(p_id text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare v_order public.orders%rowtype; v_it jsonb;
begin
  if not public.is_admin() then raise exception 'Khusus admin.'; end if;
  select * into v_order from public.orders where id = p_id for update;
  if not found then raise exception 'Pesanan tidak ditemukan.'; end if;
  if v_order.status <> 'Menunggu Verifikasi' then raise exception 'Pesanan ini sudah diproses sebelumnya.'; end if;
  for v_it in select value from jsonb_array_elements(v_order.items) loop
    update public.products set sold = sold + (v_it->>'quantity')::integer where id = (v_it->>'id')::bigint;
  end loop;
  update public.orders set status = 'Diproses' where id = p_id;
end;
$$;

-- Admin: tolak pembayaran -> Dibatalkan + stok dikembalikan ke ukuran yang sama
create or replace function public.reject_order(p_id text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare v_order public.orders%rowtype; v_it jsonb; v_prod public.products%rowtype; v_size text; v_qty integer;
begin
  if not public.is_admin() then raise exception 'Khusus admin.'; end if;
  select * into v_order from public.orders where id = p_id for update;
  if not found then raise exception 'Pesanan tidak ditemukan.'; end if;
  if v_order.status <> 'Menunggu Verifikasi' then raise exception 'Hanya pesanan yang menunggu verifikasi yang bisa ditolak.'; end if;
  for v_it in select value from jsonb_array_elements(v_order.items) loop
    v_qty  := (v_it->>'quantity')::integer;
    v_size := nullif(v_it->>'size', '');
    select * into v_prod from public.products where id = (v_it->>'id')::bigint for update;
    if not found then continue; end if;  -- produk sudah dihapus admin
    if v_prod.sizes is not null and v_size is not null and v_prod.sizes ? v_size then
      update public.products set sizes = jsonb_set(sizes, array[v_size], to_jsonb((sizes->>v_size)::integer + v_qty)) where id = v_prod.id;
    elsif v_prod.sizes is null then
      update public.products set stock = stock + v_qty where id = v_prod.id;
    end if;
  end loop;
  update public.orders set status = 'Dibatalkan' where id = p_id;
end;
$$;

-- Admin: kirim ke kurir -> Dalam Pengiriman
create or replace function public.ship_order(p_id text)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Khusus admin.'; end if;
  update public.orders set status = 'Dalam Pengiriman' where id = p_id and status = 'Diproses';
  if not found then raise exception 'Pesanan tidak dalam status Diproses.'; end if;
end;
$$;

-- Pembeli: konfirmasi barang diterima
create or replace function public.confirm_order_received(p_id text)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  update public.orders set status = 'Tiba di Tujuan'
    where id = p_id and user_id = auth.uid() and status = 'Dalam Pengiriman';
  if not found then raise exception 'Pesanan tidak bisa dikonfirmasi.'; end if;
end;
$$;

-- Pembeli: kirim ulasan untuk pesanan yang sudah tiba (sekali per pesanan)
create or replace function public.submit_review(p_order_id text, p_stars integer, p_comment text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare v_order public.orders%rowtype; v_name text; v_pid bigint;
begin
  if p_stars is null or p_stars < 1 or p_stars > 5 then raise exception 'Bintang harus 1-5.'; end if;
  if coalesce(trim(p_comment), '') = '' then raise exception 'Tuliskan ulasan Anda.'; end if;
  select * into v_order from public.orders where id = p_order_id and user_id = auth.uid() for update;
  if not found then raise exception 'Pesanan tidak ditemukan.'; end if;
  if v_order.status <> 'Tiba di Tujuan' then raise exception 'Ulasan hanya untuk pesanan yang sudah tiba.'; end if;
  if v_order.is_reviewed then raise exception 'Pesanan ini sudah diulas.'; end if;
  select name into v_name from public.profiles where id = auth.uid();

  for v_pid in select distinct (value->>'id')::bigint from jsonb_array_elements(v_order.items) loop
    if exists (select 1 from public.products where id = v_pid) then
      insert into public.reviews (product_id, order_id, user_id, user_name, stars, comment)
      values (v_pid, p_order_id, auth.uid(), coalesce(v_name, 'Pembeli'), p_stars, left(trim(p_comment), 1000));
      update public.products
        set rating = (select round(avg(r.stars)::numeric, 2) from public.reviews r where r.product_id = v_pid)
        where id = v_pid;
    end if;
  end loop;
  update public.orders set is_reviewed = true where id = p_order_id;
end;
$$;

-- Hitung view produk (boleh tanpa login)
create or replace function public.increment_view(p_product_id bigint)
returns void
language sql security definer set search_path = ''
as $$
  update public.products set views = views + 1 where id = p_product_id;
$$;

